-- Phase 2 v2 — управляемый справочник тем (theme_catalog).
--
-- SSOT тем становится таблица theme_catalog (группа -> тема), заменяя набор
-- distinct-значений meeting_series.theme_group. Существующие серии с темами вне
-- каталога НЕ трогаем (аддитивная миграция). Сев из Excel-справочника Инны:
-- 7 групп x 58 тем (лист "Справочник тем", doc_efda1ac23813_Книга5.xlsx).

create table if not exists public.theme_catalog (
  id          serial      primary key,
  group_name  text        not null,
  topic_name  text        not null,
  is_active   boolean     not null default true,
  sort_order  integer     not null default 0,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (group_name, topic_name)
);

create index if not exists idx_theme_catalog_group
  on public.theme_catalog (group_name, sort_order, topic_name);

-- updated_at trigger (reuses the shared set_updated_at() helper).
drop trigger if exists set_theme_catalog_updated_at on public.theme_catalog;
create trigger set_theme_catalog_updated_at
  before update on public.theme_catalog
  for each row execute function public.set_updated_at();

-- RLS: любой аутентифицированный участник читает справочник; пишут менеджеры
-- (глобальные админы ИЛИ те, кто управляет хотя бы одной серией) — зеркалит
-- user_can_manage_series для серий.
alter table public.theme_catalog enable row level security;

drop policy if exists theme_catalog_read on public.theme_catalog;
create policy theme_catalog_read on public.theme_catalog
  for select to authenticated using (true);

drop policy if exists theme_catalog_write on public.theme_catalog;
create policy theme_catalog_write on public.theme_catalog
  for all to authenticated
  using (
    public.user_is_global_admin()
    or exists (
      select 1 from public.meeting_series ms
      where public.user_can_manage_series(ms.id)
    )
  )
  with check (
    public.user_is_global_admin()
    or exists (
      select 1 from public.meeting_series ms
      where public.user_can_manage_series(ms.id)
    )
  );

